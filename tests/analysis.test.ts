test('密集邻域按模块聚合，保留方向、状态和完整源码证据，支持展开恢复',()=>{
  const range={start:{line:0,character:0},end:{line:0,character:1}};
  const symbols:SymbolInfo[]=Array.from({length:40},(_,i)=>({id:`s${i}`,name:`f${i}`,qualifiedName:`dense.f${i}`,signature:`f${i}()`,kind:'function',language:'python',module:'dense',file:'dense.py',range,selection:range,routes:[]}));
  const relations:Relation[]=symbols.slice(1).map((s,i)=>({id:`r${i}`,from:'s0',to:s.id,target:s.qualifiedName,type:'CALLS',source:'Pyright',status:i%2?'candidate':'resolved',locations:[{file:'dense.py',range}]}));
  relations.push({id:'reverse',from:'s39',to:'s0',target:'dense.f0',type:'CALLS',source:'Pyright',status:'resolved',locations:[{file:'dense.py',range}]});
  const index:ProjectIndex={schema:1,id:'dense',root:'D:\\fixture',name:'dense',createdAt:'test',status:'complete',languages:['python'],symbols,relations,files:[{path:'dense.py',module:'dense',language:'python',hash:'test',size:1}],diagnostics:[],versions:{},sourceRoots:[],jars:[]};
  const view:ViewState={level:'function',focus:'s0',expanded:[],positions:{},viewport:{x:0,y:0,zoom:1},filter:'all',query:''};
  const compact=graphFor(index,view);const group=compact.cards.find(c=>c.kind==='group')!;
  assert.equal(compact.cards.length,4);assert.equal(group.members?.length,37);
  assert.equal(compact.links.flatMap(l=>l.relations).length,relations.length);
  assert.ok(compact.links.some(l=>l.source===group.id&&l.target==='s0'&&l.relations.some(r=>r.id==='reverse')));
  assert.ok(compact.links.some(l=>l.target===group.id&&l.status==='candidate'));
  const expanded=graphFor(index,{...view,expanded:group.members!});
  assert.equal(expanded.cards.length,40);assert.equal(expanded.cards.filter(c=>c.kind==='group').length,0);
  assert.equal(expanded.links.flatMap(l=>l.relations).length,relations.length);
  assert.deepEqual(graphFor(index,view),compact);
  const guided=graphFor(index,{...view,entryId:'test-entry'});
  assert.ok(guided.cards.length<=15);assert.ok(guided.cards.some(c=>c.hidden?.length),'首屏预算之外的关系必须能继续展开');
  const complete=graphFor(index,{...view,entryId:'test-entry',showAll:true});
  assert.equal(complete.links.flatMap(l=>l.relations).length,relations.length,'显示全部不能丢失回路或折叠关系');
});
